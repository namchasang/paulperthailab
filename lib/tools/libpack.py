#!/usr/bin/env python3
"""Copy library items into a single-file game (or a new file) with their dependencies.

  python3 lib/tools/libpack.py OUT.js item [item ...]          write the items to a new file
  python3 lib/tools/libpack.py --into GAME.html item [item ...]  replace the block between
        /* PPL-LIB-START */ and /* PPL-LIB-END */ inside a single-file game (gamekit then re-splits it)
  e.g. python3 lib/tools/libpack.py --into golf/index.html kangaroo magpie sky-weather

Dependencies from lib/catalog.json are added automatically (kit first).
The part starts with a header naming the items and library version; re-run it to update a game
after the library changes, then `python3 tools/gamekit.py build` in that game.
"""
import json, os, sys

LIB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cat = json.load(open(os.path.join(LIB, 'catalog.json')))
items = {i['id']: i for i in cat['items']}
into = sys.argv[1] == '--into'
args = sys.argv[2:] if into else sys.argv[1:]
out, want = args[0], args[1:]
order = []
def add(i):
    it = items.get(i)
    if not it: sys.exit(f'unknown item: {i}')
    if it['status'] != 'ready': sys.exit(f'{i} is still planned (lives in {it["from"]}); move it into lib/ first')
    for d in it.get('deps', []): add(d)
    if i not in order: order.append(i)
for w in want: add(w)
parts = [f"/* ==== PPL library v{cat['version']} items: {', '.join(order)} (generated by lib/tools/libpack.py; edit the library, not this part) ==== */\n"]
for i in order:
    f = items[i].get('file', '')
    if f.endswith('.js'): parts.append(open(os.path.join(LIB, f), encoding='utf-8').read().rstrip() + '\n')
code = '/* PPL-LIB-START */\n' + ''.join(parts) + '/* PPL-LIB-END */\n'
if into:
    g = open(out, encoding='utf-8').read(); a = g.find('/* PPL-LIB-START */'); b = g.find('/* PPL-LIB-END */')
    if a < 0 or b < 0: sys.exit('markers not found in ' + out)
    g = g[:a] + code + g[b + len('/* PPL-LIB-END */\n'):]
    open(out, 'w', encoding='utf-8').write(g)
else:
    open(out, 'w', encoding='utf-8').write(code)
print(out, '<-', ', '.join(order))
